-- World War B: Bugfront cloud profile and progression schema.
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default 'PLAYER' check (char_length(display_name) between 1 and 16),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.player_progress (
  player_id uuid primary key references auth.users(id) on delete cascade,
  save_data jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

create table if not exists public.match_records (
  id bigint generated by default as identity primary key,
  player_id uuid not null references auth.users(id) on delete cascade,
  mode text not null check (mode in ('onslaught', 'deathmatch')),
  score integer not null default 0 check (score >= 0),
  elapsed_seconds integer not null default 0 check (elapsed_seconds >= 0),
  summary jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists match_records_player_created_idx on public.match_records(player_id, created_at desc);

alter table public.profiles enable row level security;
alter table public.player_progress enable row level security;
alter table public.match_records enable row level security;

drop policy if exists "profiles own row" on public.profiles;
create policy "profiles own row" on public.profiles for all using (auth.uid() = id) with check (auth.uid() = id);
drop policy if exists "progress own row" on public.player_progress;
create policy "progress own row" on public.player_progress for all using (auth.uid() = player_id) with check (auth.uid() = player_id);
drop policy if exists "matches own rows" on public.match_records;
create policy "matches own rows" on public.match_records for all using (auth.uid() = player_id) with check (auth.uid() = player_id);

create or replace function public.handle_new_user() returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (id, display_name) values (new.id, coalesce(nullif(left(new.raw_user_meta_data->>'display_name', 16), ''), 'PLAYER')) on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users for each row execute procedure public.handle_new_user();
